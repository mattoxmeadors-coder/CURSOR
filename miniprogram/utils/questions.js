// 计算评分
function calcScore(answers, gender) {
  const questions = gender === 'male' ? MALE_QUESTIONS : FEMALE_QUESTIONS
  let total = 0
  let maxTotal = 0
  const blindSpots = []
  let zeroCount = 0

  questions.forEach(q => {
    if (q.type === 'open') return
    const ans = answers[q.id]
    if (ans === undefined || ans === null) return
    const opt = q.options[ans]
    if (!opt) return
    total += opt.score
    const maxScore = Math.max(...q.options.map(o => o.score))
    maxTotal += maxScore
    if (opt.score === 0) {
      zeroCount++
      blindSpots.push({ question: q.text.substring(0, 20), stage: q.stage, analysis: q.analysis })
    } else if (opt.score <= 1 && maxScore >= 4) {
      blindSpots.push({ question: q.text.substring(0, 20), stage: q.stage, analysis: q.analysis })
    }
  })

  const percentage = maxTotal > 0 ? Math.round((total / maxTotal) * 100) : 0
  return { score: percentage, blindSpots: blindSpots.slice(0, 3), zeroCount }
}

